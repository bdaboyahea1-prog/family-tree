// Builds js/places-world.js (first-level divisions of every country, in English) from the open
// dataset "countries-states-cities-database" (github.com/dr5hn/countries-states-cities-database,
// file json/countries+states.json, licence ODbL-1.0).
//
//   node tools/build-world-places.mjs path/to/countries+states.json            (writes js/places-world.js)
//   node tools/build-world-places.mjs path/to/countries+states.json --dry      (only reports problems)
//
// Countries already written by hand in js/places-data.js (the Arab world and the usual destinations,
// in Arabic) are skipped: their Arabic lists win.
import fs from 'node:fs';
import { countryByName, countryName } from '../js/tree.js';
import { PLACES } from '../js/places-data.js';

const [src, flag] = process.argv.slice(2);
if (!src) throw new Error('usage: node tools/build-world-places.mjs countries+states.json [--dry]');
const data = JSON.parse(fs.readFileSync(src, 'utf8'));

// dataset name -> ISO code, for names that differ from the CLDR English names
const ALIASES = {
  'Ivory Coast': 'CI', 'Czech Republic': 'CZ', 'Russia': 'RU', 'South Korea': 'KR', 'North Korea': 'KP', 'Vietnam': 'VN',
  'Laos': 'LA', 'Syria': 'SY', 'Brunei': 'BN', 'Cape Verde': 'CV', 'East Timor': 'TL', 'Swaziland': 'SZ', 'Macedonia': 'MK',
  'North Macedonia': 'MK', 'Burma': 'MM', 'The Bahamas': 'BS', 'The Gambia': 'GM', 'Congo': 'CG', 'Republic of the Congo': 'CG',
  'Democratic Republic of the Congo': 'CD', 'Congo The Democratic Republic Of The': 'CD', 'Palestine': 'PS', 'Vatican City State (Holy See)': 'VA',
  'Falkland Islands': 'FK', 'Micronesia': 'FM', 'Saint Helena': 'SH', 'Saint Kitts and Nevis': 'KN', 'Saint Lucia': 'LC',
  'Saint Vincent and the Grenadines': 'VC', 'Saint Pierre and Miquelon': 'PM', 'Saint-Barthelemy': 'BL', 'Saint-Martin (French part)': 'MF',
  'Sint Maarten (Dutch part)': 'SX', 'Curaçao': 'CW', 'Reunion': 'RE', 'Aland Islands': 'AX', 'Hong Kong S.A.R.': 'HK', 'Macau S.A.R.': 'MO',
  'Libya': 'LY', 'Moldova': 'MD', 'Tanzania': 'TZ', 'Bolivia': 'BO', 'Venezuela': 'VE', 'Iran': 'IR', 'Taiwan': 'TW', 'Kosovo': 'XK',
  'Turks and Caicos Islands': 'TC', 'Virgin Islands (British)': 'VG', 'Virgin Islands (US)': 'VI', 'Wallis and Futuna Islands': 'WF',
  'Western Sahara': 'EH', 'South Sudan': 'SS', 'Sao Tome and Principe': 'ST', 'Guernsey and Alderney': 'GG', 'Bonaire, Sint Eustatius and Saba': 'BQ',
  'Svalbard And Jan Mayen Islands': 'SJ', 'Pitcairn Island': 'PN', 'Norfolk Island': 'NF', 'Cocos (Keeling) Islands': 'CC', 'Christmas Island': 'CX',
  'Cook Islands': 'CK', 'Cote D\'Ivoire (Ivory Coast)': 'CI', 'Timor-Leste': 'TL', 'Eswatini': 'SZ', 'Cabo Verde': 'CV', 'Czechia': 'CZ',
  'Northern Mariana Islands': 'MP', 'Faroe Islands': 'FO', 'Isle of Man': 'IM', 'Heard Island and McDonald Islands': 'HM',
  'South Georgia': 'GS', 'Bouvet Island': 'BV', 'French Southern Territories': 'TF', 'British Indian Ocean Territory': 'IO',
  'United States Minor Outlying Islands': 'UM', 'Antarctica': 'AQ',
  'Antigua and Barbuda': 'AG', 'Bosnia and Herzegovina': 'BA', 'Fiji Islands': 'FJ', 'Man (Isle of)': 'IM', 'Myanmar': 'MM',
  'Palestinian Territory Occupied': 'PS', 'Trinidad and Tobago': 'TT', 'Turkey': 'TR', 'Tokelau': 'TK',
};

const out = {};
const unmatched = [];
const skipped = [];
let kept = 0;
for (const c of data) {
  const code = ALIASES[c.name] || countryByName(c.name);
  if (!code) {
    unmatched.push(`${c.name} (${c.states.length} states)`);
    continue;
  }
  if (PLACES[code]) {
    skipped.push(code);
    continue;
  }
  const names = [...new Set(c.states.map((s) => String(s).trim()).filter((s) => s && s.length <= 100))].sort((a, b) => a.localeCompare(b, 'en'));
  if (!names.length) continue;
  if (out[code]) out[code] = [...new Set([...out[code], ...names])];
  else out[code] = names;
  kept += names.length;
}

console.log(`countries in file: ${data.length}`);
console.log(`taken from the dataset: ${Object.keys(out).length} countries, ${kept} provinces`);
console.log(`left to the hand-written Arabic lists: ${skipped.length} (${skipped.join(' ')})`);
console.log(`unmatched names (${unmatched.length}): ${unmatched.join('; ') || 'none'}`);
for (const code of Object.keys(out)) if (countryName(code) === code) console.log('WARNING: not a known country code:', code);

if (flag !== '--dry') {
  const lines = Object.keys(out).sort().map((code) => `  ${code}: ${JSON.stringify(out[code])},`);
  fs.writeFileSync(
    new URL('../js/places-world.js', import.meta.url),
    `// First-level divisions (provinces / states / regions) of the countries that js/places-data.js does not
// list in Arabic. English names, generated by tools/build-world-places.mjs from the open dataset
// "countries-states-cities-database" (github.com/dr5hn/countries-states-cities-database, ODbL-1.0).
// Data (c) its contributors; licence: https://opendatacommons.org/licenses/odbl/1-0/
export const WORLD = {
${lines.join('\n')}
};
`,
  );
  console.log('written js/places-world.js');
}
